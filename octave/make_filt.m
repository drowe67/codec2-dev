% make_filt.m
% David Rowe May 2015
%
% Creates low pass filter coeff used to implement a SSB/FM bandpass filters in ch

1;
graphics_toolkit ("gnuplot");
pkg load signal;

function make_afilt(name,filt_n,filt_bw,filt_centre)
    Fs = 8000;

    filt_coeff = fir1(filt_n, filt_bw/Fs);

    h = freqz(filt_coeff,1,Fs/2);
    plot(20*log10(abs(h)))
    grid minor

    % save coeffs to a C header file
    f=fopen(sprintf("../src/%sfilt_coeff.h",name),"wt");
    assert(f != -1);
    fprintf(f,"/* %d Hz LPF FIR filter coeffs */\n", filt_bw);
    fprintf(f,"/* Generated by make_filt Octave script */\n");

    fprintf(f,sprintf("\n#define %sFILT_N %d\n",upper(name), filt_n));
    fprintf(f,sprintf("\n#define %sFILT_CENTRE %d\n\n",upper(name), filt_centre));

    fprintf(f,sprintf("float %sfilt_coeff[]={\n",name));
    for r=1:filt_n
      if r < filt_n
        fprintf(f, "  %f,\n",  filt_coeff(r));
      else
        fprintf(f, "  %f\n};", filt_coeff(r));
      end
    end

    fclose(f);
endfunction

figure(1); clf;
make_afilt("ssb",100,2400,1500); % 300 - 2700 Hz
figure(2); clf;
make_afilt("fm", 100,2800,1700); % 300 - 3400 Hz

